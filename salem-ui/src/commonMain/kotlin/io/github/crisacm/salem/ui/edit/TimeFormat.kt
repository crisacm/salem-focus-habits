package io.github.crisacm.salem.ui.edit

import androidx.compose.runtime.Composable

/** Shows a time of the day the way the user's device does, and tells if its clock has 24 hours. */
class TimeFormat(val is24Hour: Boolean, private val formatter: (hour: Int, minute: Int) -> String) {
    fun format(hour: Int, minute: Int): String = formatter(hour, minute)
}

@Composable
expect fun rememberTimeFormat(): TimeFormat
