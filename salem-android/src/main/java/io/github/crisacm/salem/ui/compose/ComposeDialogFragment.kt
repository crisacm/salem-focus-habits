package io.github.crisacm.salem.ui.compose

import android.os.Bundle
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import androidx.appcompat.app.AppCompatDialogFragment
import androidx.compose.runtime.Composable
import androidx.compose.ui.platform.ComposeView
import androidx.compose.ui.platform.ViewCompositionStrategy
import io.github.crisacm.salem.R

/**
 * A DialogFragment whose content is written in Compose. It uses a transparent window, so
 * [Content] draws its own scrim and surface (see [DialogSurface]).
 */
abstract class ComposeDialogFragment : AppCompatDialogFragment() {
    @Composable
    abstract fun Content()

    override fun getTheme() = R.style.Translucent

    override fun onCreateView(
        inflater: LayoutInflater,
        container: ViewGroup?,
        savedInstanceState: Bundle?
    ): View = ComposeView(requireContext()).apply {
        setViewCompositionStrategy(ViewCompositionStrategy.DisposeOnViewTreeLifecycleDestroyed)
        setContent { SalemTheme { Content() } }
    }
}
